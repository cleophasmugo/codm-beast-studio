def _write_wav(path: Path, stereo: np.ndarray) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    data = np.clip(stereo, -1, 1)
    pcm = (data * 32767).astype("<i2")
    with wave.open(str(path), "wb") as w:
        w.setnchannels(2)
        w.setsampwidth(2)
        w.setframerate(SR)
        w.writeframes(pcm.tobytes())
    return path


def _env(n: int, attack: float, decay: float) -> np.ndarray:
    t = np.arange(n) / SR
    return np.minimum(1.0, t / max(attack, 1e-4)) * np.exp(-t / max(decay, 1e-4))


def _kick(n: int) -> np.ndarray:
    t = np.arange(n) / SR
    f = 45 + 110 * np.exp(-t * 28)
    return np.sin(2 * np.pi * np.cumsum(f) / SR) * _env(n, 0.002, 0.18)


def _snare(n: int, rng: np.random.Generator) -> np.ndarray:
    t = np.arange(n) / SR
    noise = rng.standard_normal(n) * _env(n, 0.001, 0.09)
    tone = np.sin(2 * np.pi * 190 * t) * _env(n, 0.001, 0.05)
    return 0.55 * noise + 0.45 * tone


def _hat(n: int, rng: np.random.Generator) -> np.ndarray:
    x = rng.standard_normal(n)
    x = x - np.convolve(x, np.ones(4) / 4, mode="same")  # crude high-pass
    return x * _env(n, 0.0005, 0.02)


def _tone(freq: float, n: int, kind: str = "saw") -> np.ndarray:
    t = np.arange(n) / SR
    ph = (freq * t) % 1.0
    if kind == "saw":
        return 2 * ph - 1
    if kind == "square":
        return np.sign(np.sin(2 * np.pi * freq * t))
    return np.sin(2 * np.pi * freq * t)


def _lowpass(x: np.ndarray, k: int) -> np.ndarray:
    return np.convolve(x, np.ones(k) / k, mode="same")


def _place(buf: np.ndarray, sig: np.ndarray, at: float, gain: float = 1.0) -> None:
    i = int(at * SR)
    if i >= len(buf):
        return
    j = min(len(buf), i + len(sig))
    buf[i:j] += sig[: j - i] * gain


def _note(n: int) -> float:
    return 440.0 * 2 ** ((n - 69) / 12)


def make_track(kind: str, seconds: float = 75.0, seed: int = 7) -> np.ndarray:
    rng = np.random.default_rng(seed)
    bpm = {"beast": 140.0, "neon": 118.0, "cinematic": 90.0}[kind]
    beat = 60.0 / bpm
    n = int(seconds * SR)
    drums = np.zeros(n)
    bass = np.zeros(n)
    lead = np.zeros(n)
    beats = int(seconds / beat)
    intro = 16  # beats of build-up before the drop
    prog = {"beast": [45, 45, 41, 43], "neon": [50, 46, 43, 45], "cinematic": [38, 34, 41, 36]}[kind]
    for b in range(beats):
        t = b * beat
        bar, pos = divmod(b, 4)
        root = prog[bar % 4]
        dropped = b >= intro
        if kind == "beast":
            if dropped and pos in (0, 2):
                _place(drums, _kick(int(0.4 * SR)), t, 1.0)
            if dropped and pos == 2 and bar % 2 == 1:
                _place(drums, _kick(int(0.3 * SR)), t + beat * 0.75, 0.8)
            if pos in (1, 3) and (dropped or bar % 2):
                _place(drums, _snare(int(0.25 * SR), rng), t, 0.6)
            for k in range(4 if dropped else 2):
                _place(drums, _hat(int(0.05 * SR), rng), t + k * beat / (4 if dropped else 2), 0.18)
            if dropped:
                _place(bass, _tone(_note(root - 12), int(beat * SR), "sine") * _env(int(beat * SR), 0.005, beat * 0.8),
                       t, 0.7)
        elif kind == "neon":
            if dropped:
                _place(drums, _kick(int(0.35 * SR)), t, 0.95)
            if pos in (1, 3):
                _place(drums, _snare(int(0.25 * SR), rng), t, 0.5 if dropped else 0.25)
            _place(drums, _hat(int(0.04 * SR), rng), t + beat / 2, 0.2)
            arp = [0, 7, 12, 7]
            for k, iv in enumerate(arp):
                m = int(beat / 4 * SR)
                _place(lead, _lowpass(_tone(_note(root + 12 + iv), m, "saw"), 6) * _env(m, 0.003, 0.08),
                       t + k * beat / 4, 0.16)
            m = int(beat / 2 * SR)
            for k in range(2):
                _place(bass, _lowpass(_tone(_note(root - 12), m, "saw"), 12) * _env(m, 0.005, 0.15),
                       t + k * beat / 2, 0.45 if dropped else 0.2)
        else:  # cinematic
            if pos == 0 and dropped:
                hit = _kick(int(1.2 * SR)) + 0.4 * rng.standard_normal(int(1.2 * SR)) * _env(int(1.2 * SR), 0.003, 0.3)
                _place(drums, _lowpass(hit, 3), t, 0.9)
            if dropped and pos == 2:
                _place(drums, _snare(int(0.4 * SR), rng), t, 0.45)
            if pos == 0:
                m = int(4 * beat * SR)
                pad = sum(_tone(_note(root + iv), m, "saw") for iv in (12, 15, 19)) / 3
                _place(lead, _lowpass(pad, 30) * np.minimum(1, _env(m, 0.6, 6.0)), t, 0.22)
                _place(bass, _tone(_note(root - 12), m, "sine") * _env(m, 0.05, 3.0), t, 0.5)
    mix = drums * 0.9 + bass + lead
    fade = np.ones(n)
    fl = int(2.0 * SR)
    fade[-fl:] = np.linspace(1, 0, fl)
    mix = mix * fade
    mix = mix / (np.abs(mix).max() + 1e-9) * 0.89
    width = _lowpass(lead, 2) * 0.15
    return np.stack([mix + width, mix - width], axis=1)


def make_sfx(kind: str) -> np.ndarray:
    rng = np.random.default_rng(3)
    if kind == "whoosh":
        n = int(0.45 * SR)
        x = rng.standard_normal(n)
        k = np.linspace(40, 4, n).astype(int)
        y = np.array([x[max(0, i - kk):i + 1].mean() for i, kk in zip(range(n), k)])
        env = np.sin(np.linspace(0, np.pi, n)) ** 2
        y = y * env
    elif kind == "impact":
        n = int(0.8 * SR)
        y = _kick(n) * 1.2 + 0.5 * _lowpass(rng.standard_normal(n), 6) * _env(n, 0.001, 0.12)
    else:  # riser
        n = int(1.2 * SR)
        t = np.arange(n) / SR
        y = _lowpass(rng.standard_normal(n), 3) * (t / t[-1]) ** 2 * 0.6 + \
            np.sin(2 * np.pi * np.cumsum(200 + 1200 * (t / t[-1]) ** 2) / SR) * 0.3 * (t / t[-1])
    y = y / (np.abs(y).max() + 1e-9) * 0.8
    return np.stack([y, y], axis=1)


