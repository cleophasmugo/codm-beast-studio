def generate_library_track(kind: str, dst_wav: Path) -> Path:
    return _write_wav(dst_wav, make_track(kind))


def sfx_path(cache_dir: Path, kind: str) -> Path:
    p = cache_dir / f"sfx_{kind}.wav"
    if not p.exists():
        _write_wav(p, make_sfx(kind))
    return p


def build_sfx_bed(cache_dir: Path, events: list[tuple[float, str]], total: float, dst: Path) -> Path:
    """Mix transition sound effects at the given times into one stereo WAV."""
    n = int(total * SR) + SR
    buf = np.zeros((n, 2))
    lib = {k: make_sfx(k) for k in {kind for _, kind in events}}
    for t, kind in events:
        s = lib[kind]
        start = int(max(0.0, t - (0.2 if kind == "whoosh" else 0.0)) * SR)
        end = min(n, start + len(s))
        buf[start:end] += s[: end - start] * 0.5
    return _write_wav(dst, buf[: int(total * SR)])
